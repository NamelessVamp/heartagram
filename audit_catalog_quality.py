"""Audita la calidad del catalogo maestro local de HEARTAGRAM.

No elimina juegos y no intenta afirmar que una portada fue generada por IA.
Genera una lista conservadora de registros con señales débiles para revisión.

Uso:
    python .\audit_catalog_quality.py
    python .\audit_catalog_quality.py --switch-only
    python .\audit_catalog_quality.py --limit 300

Salidas:
    data/catalog_quality_report.json
    data/catalog_quality_review.csv
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "data" / "catalog_igdb.full.json"
REPORT = ROOT / "data" / "catalog_quality_report.json"
CSV_REPORT = ROOT / "data" / "catalog_quality_review.csv"

SWITCH_PLATFORM_IDS = {130, 508}
GENERIC_TITLE_WORDS = {
    "cat", "dog", "milk", "car", "cars", "game", "games", "simulator",
    "puzzle", "runner", "racing", "adventure", "quest", "world", "hero",
}
AI_DISCLOSURE_PATTERNS = (
    "ai-generated",
    "ai generated",
    "generated by ai",
    "generative ai",
    "artificial intelligence generated",
)


def text(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def list_value(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def numeric(value: Any) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def has_platform(game: dict[str, Any], wanted: set[int]) -> bool:
    for platform in list_value(game.get("platforms")):
        if isinstance(platform, dict) and platform.get("id") in wanted:
            return True
        if isinstance(platform, int) and platform in wanted:
            return True
    return False


def company_count(game: dict[str, Any]) -> int:
    companies = list_value(game.get("involved_companies"))
    if companies:
        return len(companies)
    return len(list_value(game.get("companies")))


def media_count(game: dict[str, Any]) -> int:
    return sum(
        len(list_value(game.get(field)))
        for field in ("screenshots", "artworks", "videos")
    )


def engagement(game: dict[str, Any]) -> float:
    return max(
        numeric(game.get("total_rating_count")),
        numeric(game.get("rating_count")),
        numeric(game.get("aggregated_rating_count")),
        numeric(game.get("follows")),
        numeric(game.get("hypes")),
    )


def content_length(game: dict[str, Any]) -> int:
    return max(
        len(text(game.get("summary"))),
        len(text(game.get("storyline"))),
    )


def title_signals(title: str) -> list[str]:
    signals: list[str] = []
    clean = title.strip()
    lower = clean.lower()
    words = re.findall(r"[a-z0-9]+", lower)

    if clean and not clean[0].isalnum():
        signals.append("title_starts_with_symbol")
    if len(clean) <= 4:
        signals.append("very_short_title")
    if words and len(words) <= 3 and all(word in GENERIC_TITLE_WORDS or word.isdigit() for word in words):
        signals.append("generic_title")
    if re.search(r"\b(?:free|ultimate|best|super|amazing)\b.*\b(?:game|simulator|puzzle)\b", lower):
        signals.append("keyword_style_title")
    if re.search(r"(.)\1{4,}", lower):
        signals.append("repeated_character_title")
    return signals


def ai_disclosure(game: dict[str, Any]) -> bool:
    haystack = " ".join(
        [
            text(game.get("name")),
            text(game.get("summary")),
            text(game.get("storyline")),
        ]
    ).lower()
    return any(pattern in haystack for pattern in AI_DISCLOSURE_PATTERNS)


def evaluate(game: dict[str, Any]) -> dict[str, Any]:
    name = text(game.get("name")) or text(game.get("title")) or "Sin titulo"
    signals = title_signals(name)
    score = 0

    cover = game.get("cover")
    has_cover = bool(cover)
    companies = company_count(game)
    media = media_count(game)
    words = content_length(game)
    engagement_value = engagement(game)
    release_dates = list_value(game.get("release_dates"))
    genres = list_value(game.get("genres"))

    if has_cover:
        score += 18
    else:
        signals.append("missing_cover")

    if companies:
        score += 18
    else:
        signals.append("missing_company")

    if words >= 120:
        score += 18
    elif words >= 40:
        score += 10
    else:
        signals.append("sparse_description")

    if media >= 3:
        score += 14
    elif media:
        score += 7
    else:
        signals.append("missing_supporting_media")

    if engagement_value >= 50:
        score += 18
    elif engagement_value >= 5:
        score += 10
    elif engagement_value > 0:
        score += 4
    else:
        signals.append("no_engagement_signal")

    if release_dates:
        score += 7
    else:
        signals.append("missing_release_date")

    if genres:
        score += 7
    else:
        signals.append("missing_genres")

    title_issues = title_signals(name)
    score -= min(14, len(title_issues) * 5)

    disclosed_ai = ai_disclosure(game)
    if disclosed_ai:
        signals.append("explicit_ai_disclosure")

    score = max(0, min(100, score))

    severe_sparse = (
        not has_cover
        and companies == 0
        and words < 40
        and engagement_value == 0
    )

    if severe_sparse or score <= 20:
        recommendation = "hide_by_default"
    elif score <= 39 or len(title_issues) >= 2:
        recommendation = "manual_review"
    else:
        recommendation = "keep"

    return {
        "igdb_id": game.get("id"),
        "name": name,
        "quality_score": score,
        "recommendation": recommendation,
        "signals": sorted(set(signals)),
        "explicit_ai_disclosure": disclosed_ai,
        "has_cover": has_cover,
        "company_count": companies,
        "media_count": media,
        "description_length": words,
        "engagement_signal": engagement_value,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Audita señales de calidad del catálogo IGDB local.")
    parser.add_argument("--switch-only", action="store_true", help="Audita solo Nintendo Switch y Switch 2.")
    parser.add_argument("--limit", type=int, default=500, help="Máximo de candidatos incluidos en el CSV.")
    args = parser.parse_args()

    if not SOURCE.is_file():
        raise SystemExit("[FAIL] Falta data/catalog_igdb.full.json")

    payload = json.loads(SOURCE.read_text(encoding="utf-8-sig"))
    games = payload.get("games", []) if isinstance(payload, dict) else []
    if not isinstance(games, list):
        raise SystemExit("[FAIL] El catálogo maestro no contiene una lista games válida")

    selected = [game for game in games if isinstance(game, dict)]
    if args.switch_only:
        selected = [game for game in selected if has_platform(game, SWITCH_PLATFORM_IDS)]

    results = [evaluate(game) for game in selected]
    counts = Counter(item["recommendation"] for item in results)
    signal_counts = Counter(signal for item in results for signal in item["signals"])
    ai_disclosures = sum(1 for item in results if item["explicit_ai_disclosure"])

    review = sorted(
        (item for item in results if item["recommendation"] != "keep"),
        key=lambda item: (item["quality_score"], item["name"].lower()),
    )

    report = {
        "scope": "switch_only" if args.switch_only else "all_games",
        "evaluated": len(results),
        "recommendations": dict(counts),
        "explicit_ai_disclosures": ai_disclosures,
        "common_signals": dict(signal_counts.most_common()),
        "method_note": (
            "Este reporte mide completitud y señales de confianza del registro. "
            "No determina por sí solo si un juego o una portada fueron generados por IA."
        ),
    }
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    fields = [
        "igdb_id", "name", "quality_score", "recommendation", "signals",
        "explicit_ai_disclosure", "has_cover", "company_count", "media_count",
        "description_length", "engagement_signal",
    ]
    with CSV_REPORT.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for item in review[: max(0, args.limit)]:
            row = dict(item)
            row["signals"] = " | ".join(item["signals"])
            writer.writerow(row)

    print(f"[OK] Juegos evaluados: {len(results)}")
    print(f"[OK] Mantener: {counts.get('keep', 0)}")
    print(f"[OK] Revisión manual: {counts.get('manual_review', 0)}")
    print(f"[OK] Ocultar por defecto: {counts.get('hide_by_default', 0)}")
    print(f"[INFO] Divulgación explícita de IA encontrada: {ai_disclosures}")
    print(f"[OK] Reporte: {REPORT.relative_to(ROOT)}")
    print(f"[OK] Candidatos: {CSV_REPORT.relative_to(ROOT)}")
    print("[NOTE] Un score bajo significa metadatos débiles, no prueba de contenido generado por IA.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
